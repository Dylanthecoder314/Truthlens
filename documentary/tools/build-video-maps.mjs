// Projects Natural Earth coastlines for the documentary film's scenes and
// writes documentary/video/scenes/mapdata.js.
//
//   cd documentary/tools && npm install && node build-video-maps.mjs
//
// Every map is a 1920x1080 Mercator frame defined by a longitude span and a
// centre latitude. Land is clipped to a margin around the frame so scenes can
// pan and zoom a little without running off the coastline data.

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { geoMercator, geoPath } from "d3-geo";
import { feature, mesh } from "topojson-client";

const require = createRequire(import.meta.url);
const land50 = require("world-atlas/land-50m.json");
const countries50 = require("world-atlas/countries-50m.json");
const landGeo = feature(land50, land50.objects.land);
const borderGeo = mesh(countries50, countries50.objects.countries, (a, b) => a !== b);

const W = 1920, H = 1080, RAD = Math.PI / 180;
const MARGIN = { x: 640, y: 420 };

const MAPS = {
  // The night of 8 March: KLIA, IGARI, the turn back, last radar contact.
  night: { lonW: 93.5, lonE: 110.5, latC: 6.2, borders: true },
  // The Indian Ocean: satellite, handshake rings, Perth.
  ocean: { lonW: 15, lonE: 125, latC: -15, borders: false },
  // The southern Indian Ocean along the 7th arc: search areas.
  south: { lonW: 74, lonE: 122, latC: -30, borders: false },
  // The western Indian Ocean: where debris washed ashore.
  debris: { lonW: 12, lonE: 80, latC: -19, borders: true },
};

const merc = (lat) => Math.log(Math.tan(Math.PI / 4 + (lat * RAD) / 2));
const invMerc = (y) => (2 * Math.atan(Math.exp(y)) - Math.PI / 2) / RAD;

function pathString(decimals) {
  const f = 10 ** decimals;
  const r = (v) => Math.round(v * f) / f;
  let out = "", last = null;
  return {
    moveTo(x, y) { x = r(x); y = r(y); out += `M${x} ${y}`; last = [x, y]; },
    lineTo(x, y) {
      x = r(x); y = r(y);
      if (last && last[0] === x && last[1] === y) return;
      out += `L${x} ${y}`; last = [x, y];
    },
    closePath() { out += "Z"; last = null; },
    arc() {},
    result() { return out; },
  };
}

const data = {};
for (const [name, m] of Object.entries(MAPS)) {
  const s = W / ((m.lonE - m.lonW) * RAD);
  const tx = -s * m.lonW * RAD;
  const ty = H / 2 + s * merc(m.latC);
  // d3's Mercator: x = s·λ + tx, y = ty − s·ln tan(π/4 + φ/2) with λ, φ in radians.
  const projection = geoMercator().scale(s).translate([tx, ty])
    .clipExtent([[-MARGIN.x, -MARGIN.y], [W + MARGIN.x, H + MARGIN.y]]);
  const draw = (geo) => { const c = pathString(1); geoPath(projection, c)(geo); return c.result(); };
  data[name] = {
    w: W, h: H, s: +s.toFixed(4), tx: +tx.toFixed(4), ty: +ty.toFixed(4),
    bounds: {
      lonW: m.lonW, lonE: m.lonE,
      latN: +invMerc((ty - 0) / s).toFixed(3),
      latS: +invMerc((ty - H) / s).toFixed(3),
    },
    land: draw(landGeo),
    borders: m.borders ? draw(borderGeo) : "",
  };
}

const target = new URL("../video/scenes/mapdata.js", import.meta.url);
writeFileSync(target, `// Generated by documentary/tools/build-video-maps.mjs. Do not edit.\nwindow.MAPDATA = ${JSON.stringify(data)};\n`);
for (const [name, d] of Object.entries(data)) {
  console.log(`${name}: lat ${d.bounds.latS}..${d.bounds.latN}, lon ${d.bounds.lonW}..${d.bounds.lonE}, land ${(d.land.length / 1024).toFixed(0)} KB, borders ${(d.borders.length / 1024).toFixed(0)} KB`);
}
